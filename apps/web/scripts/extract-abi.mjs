#!/usr/bin/env node
/**
 * Emit the frontend's slice of the contract ABI as a `as const` TS module.
 *
 * wagmi/viem derive their argument and return types from the literal shape of
 * the ABI, which a JSON import throws away. Generating a TS module keeps full
 * type inference AND makes drift impossible: run with --check in CI and it
 * fails if packages/contracts/abi/Pingus2.json has moved underneath us.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, "../../../packages/contracts/abi/Pingus2.json");
const OUT = resolve(here, "../src/lib/abi.ts");

// Everything the web app actually calls. Keeping this explicit means an
// unused 60-function ABI never ships to the browser.
const WANTED = [
  "mint", "mintPrice", "totalMintedGenesis", "totalSupply", "GENESIS", "HARD_CAP",
  "RESERVE", "maxPerWallet", "mintedBy", "saleOpen", "windowOpen",
  "SALE_OPEN_AT", "SALE_CLOSE_AT", "VENTANA_I_OPEN", "VENTANA_I_CLOSE",
  "VENTANA_II_OPEN", "VENTANA_II_CLOSE",
  "calor", "estado", "generacion", "hechosCount", "bornAt", "genLocked",
  "hasBred", "parentsOf", "EL_PRIMERO", "TREASURY", "TRAITS_URI",
  "ownerOf", "balanceOf", "tokenURI", "name", "symbol",
  "encuentro", "encuentroDigest", "nonces",
  "CALOR_GEN_1", "CALOR_GEN_2", "CALOR_GEN_3",
];
const WANTED_EVENTS = ["Transfer", "Nacimiento", "Deshielo", "Encuentro", "Hecho", "Calor"];

const full = JSON.parse(readFileSync(SRC, "utf8"));
const abi = full.filter(
  (e) =>
    (e.type === "function" && WANTED.includes(e.name)) ||
    (e.type === "event" && WANTED_EVENTS.includes(e.name))
);

const missing = WANTED.filter((n) => !abi.some((e) => e.type === "function" && e.name === n));
if (missing.length) {
  console.error(`extract-abi: not in the compiled ABI: ${missing.join(", ")}`);
  process.exit(1);
}

const body = `/**
 * GENERATED by scripts/extract-abi.mjs from packages/contracts/abi/Pingus2.json.
 * Do not edit. Run \`pnpm --filter @pingus/web abi\` after changing the contract.
 */
export const pingus2Abi = ${JSON.stringify(abi, null, 2)} as const;
`;

if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(OUT, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== body) {
    console.error("extract-abi: src/lib/abi.ts is stale — run `pnpm --filter @pingus/web abi`.");
    process.exit(1);
  }
  console.log(`extract-abi: up to date (${abi.length} entries)`);
} else {
  writeFileSync(OUT, body);
  console.log(`extract-abi: wrote ${OUT} (${abi.length} entries)`);
}
